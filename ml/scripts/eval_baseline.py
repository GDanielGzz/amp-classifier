"""Evaluate the three baseline classifiers on the held-out test split.

Loads each checkpoint, predicts probabilities on the cluster-aware test
set, and produces:

  - Top-line metrics (AUC, MCC, sensitivity, specificity, F1) with
    bootstrap n=1000 95% CIs.
  - Stratified analysis by sequence length (<=20, 21-50, >50) and net
    charge at pH 7 (<=0, 0-5, >5).
  - Markdown writeup at docs/baseline_results.md.

Uses ``ml/eval_common.py`` for the bootstrap + metric machinery so the
CNN evaluator (``eval_cnn.py``, Step 8) produces directly comparable
numbers.
"""
from __future__ import annotations

import sys
from pathlib import Path

import joblib
import numpy as np
from xgboost import XGBClassifier

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from ml.eval_common import (  # noqa: E402
    LENGTH_BINS, CHARGE_BINS,
    compute_all_metrics, stratify,
    format_metrics_table, format_stratified_table,
)

PROCESSED_DIR = PROJECT_ROOT / "ml" / "data" / "processed"
CHECKPOINTS = PROJECT_ROOT / "ml" / "checkpoints"
DOCS_DIR = PROJECT_ROOT / "docs"
RESULTS_PATH = DOCS_DIR / "baseline_results.md"
TEST_CACHE = PROCESSED_DIR / "features_test.npz"

SEED = 42
N_BOOTSTRAP = 1000

MODELS = {
    "LogReg":       ("baseline_logreg.joblib", "sklearn"),
    "RandomForest": ("baseline_rf.joblib",     "sklearn"),
    "XGBoost":      ("baseline_xgb.json",      "xgb"),
}


def load_model(name: str, filename: str, kind: str):
    path = CHECKPOINTS / filename
    if not path.exists():
        print(f"[eval] missing checkpoint: {path}. Run dev.bat baseline first.")
        return None
    if kind == "sklearn":
        return joblib.load(path)
    if kind == "xgb":
        model = XGBClassifier()
        model.load_model(str(path))
        return model
    raise ValueError(f"unknown model kind: {kind}")


def predict_proba(model, X):
    """Return P(class=1) for any of the three model types."""
    proba = model.predict_proba(X)
    if proba.shape[1] == 2:
        return proba[:, 1]
    return proba.ravel()


def main():
    if not TEST_CACHE.exists():
        print(f"[eval] {TEST_CACHE} missing. Run dev.bat baseline first.")
        return 1
    data = np.load(TEST_CACHE, allow_pickle=True)
    X_test = data["X"]
    y_test = data["y"]
    lengths = data["lengths"]
    charges = data["charges"]

    # Replace NaN with column median computed on test itself (safe since
    # we don't fit any transformer here — only score).
    nan_mask = np.isnan(X_test)
    if nan_mask.any():
        col_median = np.nanmedian(X_test, axis=0)
        X_test = np.where(nan_mask, col_median, X_test)

    print(f"[eval] test set: {X_test.shape[0]} sequences, "
          f"pos={int(y_test.sum())}, neg={int((y_test == 0).sum())}")

    sections = [
        "# Baseline results",
        "",
        "*Auto-generated by `ml/scripts/eval_baseline.py`. Bootstrap n="
        f"{N_BOOTSTRAP}, seed={SEED}.*",
        "",
        f"Test set: {X_test.shape[0]} sequences "
        f"({int(y_test.sum())} positives, {int((y_test == 0).sum())} negatives) "
        "from the cluster-aware 80/10/10 split at 40% identity.",
        "",
    ]

    model_results = {}
    for model_name, (filename, kind) in MODELS.items():
        model = load_model(model_name, filename, kind)
        if model is None:
            print(f"[eval] skipping {model_name} (no checkpoint)")
            continue
        print(f"[eval] scoring {model_name} ...")
        scores = predict_proba(model, X_test)
        metrics = compute_all_metrics(y_test, scores, n_bootstrap=N_BOOTSTRAP, seed=SEED)
        length_strata = stratify(y_test, scores, lengths, LENGTH_BINS,
                                 n_bootstrap=N_BOOTSTRAP, seed=SEED)
        charge_strata = stratify(y_test, scores, charges, CHARGE_BINS,
                                 n_bootstrap=N_BOOTSTRAP, seed=SEED)
        model_results[model_name] = {
            "metrics": metrics,
            "length_strata": length_strata,
            "charge_strata": charge_strata,
        }
        print(f"  AUC: {metrics['auc']}  MCC: {metrics['mcc']}")

        sections.extend([
            f"## {model_name}",
            "",
            format_metrics_table(metrics),
            "",
            "### Stratified by length",
            "",
            format_stratified_table(length_strata, "length"),
            "",
            "### Stratified by net charge at pH 7",
            "",
            format_stratified_table(charge_strata, "charge"),
            "",
        ])

    # Head-to-head AUC table
    if model_results:
        sections.append("## Head-to-head AUC")
        sections.append("")
        rows = ["| model | AUC | MCC |", "|---|---|---|"]
        for name, res in model_results.items():
            rows.append(f"| {name} | {res['metrics']['auc']} | {res['metrics']['mcc']} |")
        sections.append("\n".join(rows))
        sections.append("")

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text("\n".join(sections) + "\n", encoding="utf-8")
    print(f"[eval] wrote {RESULTS_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
