"""Phase 2B step 3: evaluate the ESM2-head model on the held-out test split.

Auto-detects the embedding dim from the cached npz so it works for any
ESM2 variant the user picked at embed-time.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import torch

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from ml.eval_common import (  # noqa: E402
    LENGTH_BINS, CHARGE_BINS,
    compute_all_metrics, stratify,
    find_optimal_threshold,
    format_metrics_table, format_stratified_table,
)
from ml.scripts.train_esm_head import EsmHead  # noqa: E402

PROCESSED_DIR = PROJECT_ROOT / "ml" / "data" / "processed"
CHECKPOINTS = PROJECT_ROOT / "ml" / "checkpoints"
DOCS_DIR = PROJECT_ROOT / "docs"
RESULTS_PATH = DOCS_DIR / "esm_results.md"
ESM_HEAD_CHECKPOINT = CHECKPOINTS / "esm_head_best.pt"

SEED = 42
N_BOOTSTRAP = 1000


def score_batch(model, X, device, batch_size=128):
    out = []
    with torch.no_grad():
        for i in range(0, X.shape[0], batch_size):
            xb = X[i:i + batch_size].to(device)
            logits = model(xb)
            out.append(torch.sigmoid(logits).cpu().numpy())
    return np.concatenate(out)


def main():
    if not ESM_HEAD_CHECKPOINT.exists():
        print(f"[eval-esm] {ESM_HEAD_CHECKPOINT} missing. Run dev.bat esm-train first.")
        return 1
    val_cache = PROCESSED_DIR / "esm_val.npz"
    test_cache = PROCESSED_DIR / "esm_test.npz"
    if not val_cache.exists() or not test_cache.exists():
        print("[eval-esm] esm_val.npz or esm_test.npz missing. Run dev.bat esm-embed first.")
        return 1

    val = np.load(val_cache, allow_pickle=True)
    test = np.load(test_cache, allow_pickle=True)
    in_dim = int(val["X"].shape[1])
    model_name = str(val.get("model_name", "unknown"))

    X_val = torch.from_numpy(val["X"].astype(np.float32))
    y_val = val["y"].astype(int)
    X_test = torch.from_numpy(test["X"].astype(np.float32))
    y_test = test["y"].astype(int)
    lengths = test["lengths"]
    charges = test["charges"]

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[eval-esm] device={device}, ESM model={model_name}, embedding_dim={in_dim}")
    print(f"[eval-esm] test: {X_test.shape[0]} sequences "
          f"({int((y_test == 1).sum())} pos / {int((y_test == 0).sum())} neg)")

    checkpoint = torch.load(ESM_HEAD_CHECKPOINT, map_location=device, weights_only=False)
    ckpt_dim = checkpoint.get("in_dim", in_dim)
    if ckpt_dim != in_dim:
        print(f"[eval-esm] ERROR: checkpoint expects in_dim={ckpt_dim} but cached embeddings are {in_dim}.")
        print("[eval-esm] Re-run `dev.bat esm-train` against the current embeddings.")
        return 1
    model = EsmHead(in_dim=in_dim).to(device)
    model.load_state_dict(checkpoint["state_dict"])
    model.eval()
    print(f"[eval-esm] loaded epoch {checkpoint.get('epoch', '?')}, "
          f"val_auc={checkpoint.get('val_auc', '?')}")

    val_scores = score_batch(model, X_val, device)
    test_scores = score_batch(model, X_test, device)

    tuned_t, tuned_val_mcc = find_optimal_threshold(y_val, val_scores, metric="mcc")
    print(f"[eval-esm] tuned MCC threshold (val): t={tuned_t:.3f}  val_MCC={tuned_val_mcc:.3f}")

    metrics_default = compute_all_metrics(
        y_test, test_scores, n_bootstrap=N_BOOTSTRAP, seed=SEED, threshold=0.5,
    )
    metrics_tuned = compute_all_metrics(
        y_test, test_scores, n_bootstrap=N_BOOTSTRAP, seed=SEED, threshold=tuned_t,
    )
    length_strata = stratify(
        y_test, test_scores, lengths, LENGTH_BINS,
        n_bootstrap=N_BOOTSTRAP, seed=SEED, threshold=0.5,
    )
    charge_strata = stratify(
        y_test, test_scores, charges, CHARGE_BINS,
        n_bootstrap=N_BOOTSTRAP, seed=SEED, threshold=0.5,
    )
    print(f"[eval-esm] AUC: {metrics_default['auc']}  "
          f"MCC@0.5: {metrics_default['mcc']}  MCC@tuned: {metrics_tuned['mcc']}")

    sections = [
        "# ESM2 head results",
        "",
        f"*Auto-generated by `ml/scripts/eval_esm_head.py`. Bootstrap n="
        f"{N_BOOTSTRAP}, seed={SEED}.*",
        "",
        f"Backbone (frozen): `{model_name}` ({in_dim}-dim mean-pooled embedding).",
        "",
        f"Head: small MLP (in -> max(128,in/2) -> max(64,in/4) -> 1, BatchNorm "
        f"+ Dropout 0.3) trained with BCE+pos_weight, AdamW lr=1e-3, "
        f"early stop on val AUC patience 15.",
        "",
        f"Checkpoint: epoch {checkpoint.get('epoch', '?')}, "
        f"val AUC {checkpoint.get('val_auc', float('nan')):.4f}.",
        "",
        "## Top-line metrics (threshold = 0.5)",
        "",
        format_metrics_table(metrics_default),
        "",
        f"## Same metrics at val-tuned threshold (t = {tuned_t:.3f})",
        "",
        format_metrics_table(metrics_tuned),
        "",
        "### Stratified by length (t=0.5)",
        "",
        format_stratified_table(length_strata, "length"),
        "",
        "### Stratified by net charge at pH 7 (t=0.5)",
        "",
        format_stratified_table(charge_strata, "charge"),
        "",
        "## Comparison with baselines and CNN",
        "",
        "See `docs/baseline_results.md`, `docs/cnn_results.md`, and the "
        "unified table in `docs/model_card.md`.",
        "",
    ]

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text("\n".join(sections) + "\n", encoding="utf-8")
    print(f"[eval-esm] wrote {RESULTS_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
