"""Phase 2C step 3: evaluate the multi-label activity head on the test split.

Per-class AUC + bootstrap CIs + macro-AUC. Also reports per-class
positive counts in test so the antiparasitic class's wide CI is
visible alongside its number (~8 positives in test split).

Writes docs/multiclass_results.md.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import torch

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from ml.eval_common import bootstrap_metric, MetricWithCI  # noqa: E402
from ml.scripts.train_esm_multiclass import (  # noqa: E402
    MultiClassHead, ACTIVITY_CLASSES,
    load_id_to_dramp_map, load_activities, filter_amp_with_labels,
)

PROCESSED_DIR = PROJECT_ROOT / "ml" / "data" / "processed"
CHECKPOINTS = PROJECT_ROOT / "ml" / "checkpoints"
DOCS_DIR = PROJECT_ROOT / "docs"
RESULTS_PATH = DOCS_DIR / "multiclass_results.md"
MULTICLASS_CKPT = CHECKPOINTS / "esm_multiclass_head.pt"

SEED = 42
N_BOOTSTRAP = 1000


def score_batch(model, X, device, batch_size=128):
    out = []
    with torch.no_grad():
        for i in range(0, X.shape[0], batch_size):
            xb = X[i:i + batch_size].to(device)
            logits = model(xb)
            out.append(torch.sigmoid(logits).cpu().numpy())
    return np.concatenate(out)


def main():
    if not MULTICLASS_CKPT.exists():
        print(f"[eval-mc] {MULTICLASS_CKPT} missing. Run dev.bat multiclass first.")
        return 1
    test_cache = PROCESSED_DIR / "esm_test.npz"
    if not test_cache.exists():
        print(f"[eval-mc] {test_cache} missing. Run dev.bat esm first.")
        return 1

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    id_to_dramp = load_id_to_dramp_map()
    activities = load_activities()
    X_test, Y_test, ids_test = filter_amp_with_labels(test_cache, id_to_dramp, activities)
    in_dim = int(X_test.shape[1])
    print(f"[eval-mc] device={device}, in_dim={in_dim}, "
          f"test AMP positives={len(X_test)}")

    checkpoint = torch.load(MULTICLASS_CKPT, map_location=device, weights_only=False)
    classes = checkpoint.get("classes", list(ACTIVITY_CLASSES))
    model = MultiClassHead(in_dim=in_dim, n_classes=len(classes)).to(device)
    model.load_state_dict(checkpoint["state_dict"])
    model.eval()
    print(f"[eval-mc] loaded epoch {checkpoint.get('epoch','?')}, "
          f"val_macro_auc={checkpoint.get('val_macro_auc','?')}")

    X_test_t = torch.from_numpy(X_test)
    scores = score_batch(model, X_test_t, device)

    per_class = {}
    print(f"[eval-mc] per-class test AUC (bootstrap n={N_BOOTSTRAP}):")
    macro_aucs = []
    for i, c in enumerate(classes):
        n_pos = int(Y_test[:, i].sum())
        n_neg = int((Y_test[:, i] == 0).sum())
        if n_pos < 5 or n_neg < 5:
            per_class[c] = {
                "n_pos": n_pos, "n_neg": n_neg,
                "auc": MetricWithCI(point=float("nan"),
                                     ci_low=float("nan"), ci_high=float("nan")),
                "note": f"skipped (n_pos={n_pos}, n_neg={n_neg}; need >=5 of each)",
            }
            print(f"  {c}: SKIPPED (n_pos={n_pos}, n_neg={n_neg})")
            continue
        auc = bootstrap_metric(Y_test[:, i].astype(int), scores[:, i],
                                metric="auc", n_bootstrap=N_BOOTSTRAP, seed=SEED)
        per_class[c] = {"n_pos": n_pos, "n_neg": n_neg, "auc": auc}
        if not (np.isnan(auc.point) or np.isnan(auc.ci_low)):
            macro_aucs.append(auc.point)
        print(f"  {c}: AUC {auc}  (n_pos={n_pos}, n_neg={n_neg})")

    macro_auc = float(np.mean(macro_aucs)) if macro_aucs else float("nan")
    print(f"[eval-mc] macro-AUC (mean of finite per-class AUCs): {macro_auc:.4f}")

    sections = [
        "# Multi-label activity head — results",
        "",
        f"*Auto-generated by `ml/scripts/eval_esm_multiclass.py`. "
        f"Bootstrap n={N_BOOTSTRAP}, seed={SEED}.*",
        "",
        f"Architecture: same 3-layer MLP head as the binary Phase 2B model, "
        f"but with {len(classes)} sigmoid outputs (multi-label). Trained on "
        f"the AMP-positive subset of the cluster-aware splits, using ESM2-650M "
        f"frozen embeddings as input.",
        "",
        f"Checkpoint: epoch {checkpoint.get('epoch','?')}, "
        f"val macro-AUC {checkpoint.get('val_macro_auc', float('nan')):.4f}.",
        "",
        f"## Per-class test AUC (n={len(X_test)} AMP positives in held-out test)",
        "",
        "| activity | n_pos | n_neg | AUC (95% CI) |",
        "|---|---|---|---|",
    ]
    for c in classes:
        d = per_class[c]
        if "note" in d:
            sections.append(f"| {c} | {d['n_pos']} | {d['n_neg']} | {d['note']} |")
        else:
            sections.append(f"| {c} | {d['n_pos']} | {d['n_neg']} | {d['auc']} |")
    sections.extend([
        "",
        f"**Macro-AUC** (mean over classes with sufficient test positives): "
        f"**{macro_auc:.4f}**",
        "",
        "## Honest caveats",
        "",
        "- **antibacterial** dominates the DRAMP positives (~96%). Its AUC is "
        "close to the binary AMP-vs-non-AMP problem at the input side; high "
        "AUC here is mostly a re-derivation of the Phase 2B result.",
        "- **antifungal** and **antiviral** carry ~17-19% of positives each "
        "and are where the multi-label head earns its keep — these are real "
        "minority classes the binary model can't distinguish.",
        "- **antiparasitic** has only ~8 positives in the held-out test set "
        "(81 total, 80/10/10 split). The CI is correspondingly wide; treat "
        "any reported AUC for this class with caution. A future Phase 2C-v2 "
        "should either pool antiparasitic with another rare class (e.g. "
        "anti-protozoal under a unified 'eukaryotic-pathogen' label) or "
        "explicitly drop it from v1.",
        "",
    ])

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text("\n".join(sections) + "\n", encoding="utf-8")
    print(f"[eval-mc] wrote {RESULTS_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
